"""生成《v9.4量化参数表.xlsx》.

基于 v9.3 量化参数表.xlsx 新增:
  - sheet 'v9.4修订说明': v9.4 关闭的 3 项硬缺口 + 补充的 P1/P2 项
  - 不覆盖 v9.3 原文件.
"""
from __future__ import annotations

from pathlib import Path

import openpyxl

SRC = Path("300万计划/v9.3量化参数表.xlsx")
DST = Path("300万计划/v9.4量化参数表.xlsx")


def main() -> None:
    wb = openpyxl.load_workbook(str(SRC))

    # --- v9.4 修订说明 sheet ---
    rs = wb.create_sheet("v9.4修订说明")
    rs.append(["编号", "修订项", "说明"])
    fixes = [
        ("1", "单边上涨对向条款", "§五 新增: 批二 60 万权益弹药对向投入条款(沪深300 收于 250 日线上方且走平转上连续 20 交易日，分 3 批投入) + 时间窗失效规则(连续 30 个交易日未触发则失效)"),
        ("2", "IV Rank 操作定义", "§二 新增: IV Rank 采用平值 3M IV、2 年窗口、数据源=量化系统期权模块，明确四档阈值(0-25/25-50/50-75/75-100)"),
        ("3", "清理 §九 残留矛盾", "删除 §九 正文残留的 v9.1 旧五阶段叙述(\"极端熊市投 50 万\"已被修订记录⑤废除)，与 §五 新建仓矩阵保持一致"),
        ("4", "保证金分账", "§六 新增: 60 万现金层分账为 30 万期权保证金 + 30 万现金储备，设置期权保证金红线 25 万"),
        ("5", "卫星说明书", "§九 新增: ETF Score 池子项信号定义(趋势/波动/流动性/成本)、持仓规则(权重上限 15%)、换手率阈值(月度 20%)"),
        ("6", "前置验收+期限重述", "§八 新增: 真实券商上线前置验收清单(QMT客户端/账号/enable配置)，重述\"满仓约 2027 春\"为\"预计 2027 年 3 月底完成全仓投入\""),
        ("7", "滚动+指派 SOP", "§十 新增: 卫星组合滚动 SOP(月度调仓/季度重平衡) + 指派规则(主账户 70%/卫星 30%)"),
        ("8", "佣金预算行", "§三 新增: 期权交易佣金预算行(按 0.3‰ 估算，年化约 1.8 万)"),
    ]
    for r in fixes:
        rs.append(list(r))

    # 把新 sheet 移到合适位置 (放在最前两张之后)
    wb.move_sheet("v9.4修订说明", offset=-len(wb.sheetnames) + 3)

    wb.save(str(DST))
    print("已生成:", DST)
    print("sheets:", wb.sheetnames)


if __name__ == "__main__":
    main()